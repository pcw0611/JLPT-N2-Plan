def clean_anchor(anchor, before):
    if anchor == 'の' or anchor == 'な':
        return anchor
    anchor = re.sub(r'^(?:明日の|費用の|の|少し|毎日|窓が|部屋は|この|その|あの|どんなに|私)', '', anchor)
    if not anchor:
        anchor = before[-2:]
    return anchor

