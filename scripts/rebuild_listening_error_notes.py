def main():
    print("[1] Fetching all notes from deck:", DECK_LISTENING)
    res = mcp_call('find_notes', {'query': f'deck:"{DECK_LISTENING}"'})
    note_ids = res.get('structuredContent', {}).get('noteIds', [])
    print(f"    Found {len(note_ids)} notes in Anki deck.")
    assert len(note_ids) == 25, f"Expected 25 notes, got {len(note_ids)}"

    info_res = mcp_call('notes_info', {'notes': note_ids})
    notes = info_res.get('structuredContent', {}).get('notes', [])

    # Index cards by (exam, qid)
    card_map = {(c['exam'], c['qid']): c for c in ALL_25_LISTENING_CARDS}

    updated_count = 0
    tsv_rows = []

    for n in notes:
        nid = n['noteId']
        tags = n.get('tags', [])
        exam_tag = '1회_공식제2집' if '1회_공식제2집' in tags else '2회_202312'
        qid = None
        for t in tags:
            if t.startswith('Q') and t[1:].isdigit():
                qid = int(t[1:])
                break

        if not qid or (exam_tag, qid) not in card_map:
            print(f"[ERROR] Cannot match note {nid} with tags: {tags}")
            continue

        c_data = card_map[(exam_tag, qid)]
        front_html, back_html, final_tags = generate_card_html(c_data)

        # Call MCP update_note_fields
        up_res = mcp_call('update_note_fields', {
            'id': nid,
            'fields': {
                'Front': front_html,
                'Back': back_html
            }
        })
        if up_res and not up_res.get('isError'):
            updated_count += 1
            print(f"  [OK] Updated Note {nid} -> {exam_tag} Q{qid} (Ans: {c_data['answer_idx']+1}番 {c_data['choices'][c_data['answer_idx']]})")
        else:
            print(f"  [FAIL] Failed to update Note {nid}: {up_res}")

        # Clean for TSV export
        tsv_front = front_html.replace('\t', ' ').replace('\n', '<br>')
        tsv_back = back_html.replace('\t', ' ').replace('\n', '<br>')
        tsv_tags = " ".join(final_tags)
        tsv_rows.append(f"{tsv_front}\t{tsv_back}\t{tsv_tags}")

    print(f"\n[2] Total successfully updated: {updated_count}/25")
    assert updated_count == 25, f"Expected 25 updated, got {updated_count}"

    # Write backup TSV
    tsv_path = 'anki_error_notes_listening_25.tsv'
    with open(tsv_path, 'w', encoding='utf-8') as f:
        f.write("\n".join(tsv_rows))
    print(f"[3] Exported authentic data to {tsv_path} ({len(tsv_rows)} rows)")

    # Trigger Anki sync
    print("[4] Triggering AnkiWeb sync...")
    sync_res = mcp_call('sync')
    job_id = sync_res.get('structuredContent', {}).get('job_id')
    if job_id:
        for _ in range(15):
            time.sleep(2)
            poll = mcp_call('sync', {'job_id': job_id})
            st = poll.get('structuredContent', {}).get('status')
            if st in ['success', 'error', 'conflict', 'cancelled']:
                print(f"    Sync status: {st}")
                break

    print("\n" + "="*70)
    print(">>> ALL 25 LISTENING ERROR NOTES FULLY VERIFIED, REBUILT & SYNCED! <<<")
    print("="*70)

if __name__ == '__main__':
    main()

