def clean(value: str) -> str:
    return html.escape(value).replace("\n", "<br>")


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    deck = genanki.Deck(208310025, "JLPT N2::문법 001-025 예문 복습")

    with TSV_PATH.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.writer(handle, delimiter="\t")
        writer.writerow([
            "ID", "문형", "짧은 뜻", "접속", "핵심 의미", "예문 1", "예문 1 해석",
            "예문 2", "예문 2 해석", "구별 포인트", "시험 신호", "Tags",
        ])
        for row in CARDS:
            number, pattern, connection, meaning, ex1, tr1, ex2, tr2, contrast, signal = row
            priority = "priority_high" if number in {"009", "010", "011", "012", "013", "014", "015", "016", "017", "019", "022"} else "priority_normal"
            tags = ["JLPT_N2", "문법_001_025", f"문법_{number}", priority]
            note = genanki.Note(
                model=MODEL,
                fields=[clean(row[0]), clean(row[1]), clean(GLOSSES[number]), *[clean(value) for value in row[2:]]],
                tags=tags,
                guid=genanki.guid_for("jlpt-n2-grammar-001-025", number),
            )
            deck.add_note(note)
            writer.writerow([row[0], row[1], GLOSSES[number], *row[2:], " ".join(tags)])

    genanki.Package(deck).write_to_file(str(APKG_PATH))
    print(f"Created {APKG_PATH}")
    print(f"Created {TSV_PATH}")
    print(f"Notes: {len(CARDS)}")


if __name__ == "__main__":
    main()
