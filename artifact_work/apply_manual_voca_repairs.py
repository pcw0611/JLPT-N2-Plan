def main() -> None:
    candidate_path = OUTPUT / "candidates.json"
    translation_path = OUTPUT / "translations-ko.json"
    candidates = json.loads(candidate_path.read_text(encoding="utf-8"))
    payload = json.loads(translation_path.read_text(encoding="utf-8"))
    translations = payload["translations"]

    seen: set[str] = set()
    for item in candidates:
        repair = REPAIRS.get(item["id"])
        if not repair:
            continue
        japanese, korean = repair
        old_japanese = item["japanese"]
        item.update({
            "japanese": japanese,
            "english": None,
            "source_id": None,
            "repaired_from": old_japanese,
            "repair_kind": "direct_authored",
        })
        reviewed_highlights = {
            "JLPT-한끝-N4-035": "いくら検討しても",
            "JLPT-한끝-N5-372": "ひこうき",
        }
        if item["id"] in reviewed_highlights:
            item["highlight_surface"] = reviewed_highlights[item["id"]]
        translations[japanese] = korean
        seen.add(item["id"])

    missing_repairs = sorted(set(REPAIRS) - seen)
    if missing_repairs:
        raise RuntimeError(f"Repair IDs not found: {missing_repairs}")

    reviewed_existing_highlights = {
        "JLPT-한끝-N2-0662": "総売上",
        "JLPT-한끝-N3-498": "りっぱだった",
        "JLPT-한끝-N5-115": "かんたんだった",
        "JLPT-한끝-N5-462": "りっぱだった",
    }
    for item in candidates:
        if item["id"] in reviewed_existing_highlights:
            item["highlight_surface"] = reviewed_existing_highlights[item["id"]]

    # Remove parenthetical Japanese spellings that the model added after Korean names.
    for source, target in list(translations.items()):
        translations[source] = re.sub(
            r"\([^)]*[\u3040-\u30ff\u3400-\u4dbf\u4e00-\u9fff][^)]*\)",
            "",
            target,
        ).strip()
    translations.update(TRANSLATION_CORRECTIONS)

    payload["translations"] = translations
    payload["direct_authored_repairs"] = len(REPAIRS)
    payload["direct_reviewed_translation_corrections"] = len(TRANSLATION_CORRECTIONS)
    candidate_path.write_text(json.dumps(candidates, ensure_ascii=False, indent=2), encoding="utf-8")
    translation_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"repaired": len(REPAIRS)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
